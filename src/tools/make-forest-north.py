#!/usr/bin/env python3
"""THE FOREST THE OWNER JUST SPECIFIED (2026-10-17):

    "你把柱子，放到y大于0的地方，x(-5,5)，y(0,20)，起点周围不要有柱子。柱子0.5m格子随机生成。柱子半径0.1m"

  * the forest stands only where y > 0: x in (-5, 5), y in (0, 20) -- 10 m wide, 20 m long;
  * a 0.5 m lattice, ONE pillar of radius **0.10 m** per cell, at a RANDOM position anywhere in its cell
    (the owner's standing instruction "抖动拉满": the jitter budget is the whole half-cell, 0.25 m);
  * no pillars around the START point: a free disc of 1.1 m radius about the origin;
  * z 0 -> 10 m; the arena walls follow the forest region.

The mission block is COPIED from worlds/rect68_random.yaml unchanged (the 9-waypoint two-lap 6 x 8 m tour), because
the owner changed the forest and not the mission.

usage: src/tools/make-forest-north.py     (writes worlds/forest_north.yaml)
"""
import os
import random

import numpy as np
import yaml

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CELL, R, SEED = 0.5, 0.10, 7
X0, X1, Y0, Y1 = -5.0, 5.0, 0.0, 20.0
PAD_FREE = 1.1          # free disc about the start point
Z0, Z1 = 0.0, 10.0

rng = random.Random(SEED)
nx = int(round((X1 - X0) / CELL))
ny = int(round((Y1 - Y0) / CELL))
pillars, dropped_pad = [], 0
for i in range(nx):
    for j in range(ny):
        cx = X0 + (i + 0.5) * CELL
        cy = Y0 + (j + 0.5) * CELL
        lim = (CELL - 2.0 * R) / 2.0                 # the whole half-cell: jitter is maximal
        px = cx + rng.uniform(-lim, lim)
        py = cy + rng.uniform(-lim, lim)
        if np.hypot(px, py) - R < PAD_FREE:          # the start point's own clearing
            dropped_pad += 1
            continue
        pillars.append((px, py))
P = np.array(pillars)
d = np.sqrt(((P[:, None, :] - P[None, :, :]) ** 2).sum(-1))
np.fill_diagonal(d, 1e9)
print("FOREST NORTH -- x (%.0f, %.0f), y (%.0f, %.0f), %.2f m cells, r %.2f m" % (X0, X1, Y0, Y1, CELL, R))
print("  pillars %d of %d cells (%d dropped for the start clearing)" % (len(P), nx * ny, dropped_pad))
print("  nearest neighbour %.3f m centre / %.3f m surface" % (d.min(), d.min() - 2 * R))
print("  jitter budget %.3f m (the whole half-cell)" % ((CELL - 2 * R) / 2))

base = yaml.safe_load(open(os.path.join(REPO, "worlds", "rect68_random.yaml")))
head = """\
# GENERATED by src/tools/make-forest-north.py (2026-10-17) from the owner's specification:
#   "你把柱子，放到y大于0的地方，x(-5,5)，y(0,20)，起点周围不要有柱子。柱子0.5m格子随机生成。柱子半径0.1m"
# Re-run it rather than editing the list:  python3 src/tools/make-forest-north.py
#
# THE RULE: a {cell} m lattice over x in ({x0}, {x1}), y in ({y0}, {y1}); one pillar of radius {r} m per cell at a
# RANDOM position anywhere in it (jitter = the whole half-cell, {lim} m); nothing within {pad} m of the start point's
# surface; z {z0} -> {z1} m (no over-the-top).  MEASURED: {n} pillars, nearest neighbour {nn:.3f} m centre /
# {nns:.3f} m surface.  The mission block is copied from worlds/rect68_random.yaml: the tour is unchanged.
""".format(cell=CELL, x0=X0, x1=X1, y0=Y0, y1=Y1, r=R, lim=(CELL - 2 * R) / 2, pad=PAD_FREE,
           z0=Z0, z1=Z1, n=len(P), nn=d.min(), nns=d.min() - 2 * R)

body = {"pillars": [{"x": round(float(x), 3), "y": round(float(y), 3), "r": R, "z0": Z0, "z1": Z1}
                    for x, y in P]}
body["spawn"] = base["spawn"]
body["pad"] = base["pad"]
arena = dict(base["arena"])
arena["walls"] = {"x": [X0, X1], "y": [Y0, Y1]}
body["arena"] = arena
body["sensor"] = base["sensor"]
body["imu"] = base["imu"]
mission = dict(base["mission"])
mission["name"] = "forest_north"
mission["note"] = ("MISSION B on the owner's NORTH FOREST (2026-10-17): 0.5 m cells with one r = 0.10 m pillar per "
                   "cell at a random position, only where y > 0, and nothing within 1.1 m of the start point.  The "
                   "9-waypoint two-lap tour is unchanged.")
body["mission"] = mission
body["mission_b"] = base["mission_b"]
body["fake_truth"] = base["fake_truth"]
body["meta"] = {"note": "North forest (y > 0) per the owner's specification; generated by src/tools/make-forest-north.py."}

out = os.path.join(REPO, "worlds", "forest_north.yaml")
with open(out, "w", encoding="utf-8") as f:
    f.write(head)
    yaml.safe_dump(body, f, sort_keys=False, default_flow_style=None, width=110)
print("wrote %s" % out)

# the tour's clearance on THIS field, which is what decides whether it can be flown
w = yaml.safe_load(open(out))
P = np.array([[p["x"], p["y"]] for p in w["pillars"]])
R = w["pillars"][0]["r"]
C = np.array([[c[0], c[1]] for c in w["mission"]["corners"]], float)
legs = []
for k in range(len(C) - 1):
    ss = np.linspace(0, 1, 600)[:, None]
    pts = C[k][None, :] + ss * (C[k + 1] - C[k])[None, :]
    legs.append(float(np.min(np.sqrt(((pts[:, None, :] - P[None, :, :]) ** 2).sum(-1)) - R)))
corners = [float(np.min(np.sqrt(((c[None, :] - P) ** 2).sum(1)) - R)) for c in C]
print("  the tour on this field: legs %s" % " ".join("%+.3f" % v for v in legs))
print("                          worst leg %+.3f m, worst corner %+.3f m" % (min(legs), min(corners)))
