#!/usr/bin/env python3
"""MISSION C'S SCENE, AS THE OWNER JUST SPECIFIED IT:

    "改柱子林，y(-2,20),x(-6,6)范围生成柱子林，每0.6m的格子，最大化随机采样，随机生成一根0.12m半径的柱子。
     把这个设置为c任务的默认场景，重新飞。"

  * the forest stands in x in (-6, 6), y in (-2, 20) -- the pad is now INSIDE it, not on its edge;
  * 0.6 m cells, ONE pillar of r = 0.12 m per cell at a RANDOM position anywhere in it (jitter = the whole half-cell,
    (0.6 - 0.24)/2 = 0.18 m) -- the owner's standing "maximise the randomness";
  * a clearing round the start point (nothing within 0.8 m of the pad's surface), kept because the pad has to be able
    to sit and land;
  * pillars 3 m tall (the owner's earlier instruction), arena ceiling 10.5 m -- the 5 m ceiling of the last version made
    33 % of the scan ceiling returns at 2 m altitude (STATUS 264), which is a sensor artefact, not the scene the owner
    asked for;
  * z 0 -> 3 m.

usage: src/tools/make-forest-north.py     (writes worlds/forest_north.yaml)
"""
import os
import random

import numpy as np
import yaml

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CELL, R, SEED = 0.6, 0.12, 7
X0, X1, Y0, Y1 = -6.0, 6.0, -2.0, 20.0
PAD_FREE = 0.80
Z0, Z1 = 0.0, 3.0
CEIL = 10.5

rng = random.Random(SEED)
nx = int(round((X1 - X0) / CELL))
ny = int(round((Y1 - Y0) / CELL))
lim = (CELL - 2.0 * R) / 2.0                 # maximise the jitter: the whole half-cell
pillars, dropped_pad = [], 0
for i in range(nx):
    for j in range(ny):
        cx = X0 + (i + 0.5) * CELL
        cy = Y0 + (j + 0.5) * CELL
        px = cx + rng.uniform(-lim, lim)
        py = cy + rng.uniform(-lim, lim)
        if np.hypot(px, py) - R < PAD_FREE:
            dropped_pad += 1
            continue
        pillars.append((px, py))
P = np.array(pillars)
d = np.sqrt(((P[:, None, :] - P[None, :, :]) ** 2).sum(-1))
np.fill_diagonal(d, 1e9)
print("FOREST NORTH -- x (%g, %g), y (%g, %g), %.2f m cells, r %.2f m, jitter %.3f m"
      % (X0, X1, Y0, Y1, CELL, R, lim))
print("  pillars %d of %d cells (%d dropped for the start clearing)" % (len(P), nx * ny, dropped_pad))
print("  nearest neighbour %.3f m centre / %.3f m surface" % (d.min(), d.min() - 2 * R))

base = yaml.safe_load(open(os.path.join(REPO, "worlds", "forest_north.yaml")))
head = """\
# GENERATED by src/tools/make-forest-north.py (2026-10-17, second revision) from the owner's specification:
#   "改柱子林，y(-2,20),x(-6,6)范围生成柱子林，每0.6m的格子，最大化随机采样，随机生成一根0.12m半径的柱子。
#    把这个设置为c任务的默认场景，重新飞。"
# Re-run it rather than editing the list:  python3 src/tools/make-forest-north.py
#
# THE RULE: a {cell} m lattice over x in ({x0}, {x1}), y in ({y0}, {y1}); one pillar of radius {r} m per cell at a
# RANDOM position anywhere in it (jitter = the whole half-cell, {lim} m); nothing within {pad} m of the start point's
# surface; pillars {z1} m tall, arena ceiling {ceil} m.  MEASURED: {n} pillars, nearest neighbour {nn:.3f} m centre /
# {nns:.3f} m surface.  The mission block is copied: the tour is unchanged.
""".format(cell=CELL, x0=X0, x1=X1, y0=Y0, y1=Y1, r=R, lim=lim, pad=PAD_FREE, z1=Z1, ceil=CEIL,
           n=len(P), nn=d.min(), nns=d.min() - 2 * R)

body = dict(base)
body["pillars"] = [{"x": round(float(x), 3), "y": round(float(y), 3), "r": R, "z0": Z0, "z1": Z1} for x, y in P]
body["arena"] = dict(base["arena"])
body["arena"]["walls"] = {"x": [X0, X1], "y": [Y0, Y1]}
body["arena"]["ceiling_z"] = CEIL
body["mission"]["name"] = "forest_north"
body["mission"]["note"] = ("MISSION C (owner, 2026-10-17 second revision): the forest fills x (-6, 6), y (-2, 20) on a "
                           "0.6 m lattice with one r = 0.12 m pillar per cell at a random position anywhere in it; "
                           "nothing within 0.8 m of the start point; pillars 3 m tall.  Tour unchanged: "
                           "(0,0,2.0) -> (0,1.5) -> (0,3.0) -> (0,5.0).")
body["meta"] = {"note": "Mission C's default scene, generated by src/tools/make-forest-north.py."}

out = os.path.join(REPO, "worlds", "forest_north.yaml")
with open(out, "w", encoding="utf-8") as f:
    f.write(head)
    yaml.safe_dump(body, f, sort_keys=False, default_flow_style=None, width=110)
print("wrote %s" % out)

w = yaml.safe_load(open(out))
P2 = np.array([[p["x"], p["y"]] for p in w["pillars"]])
print("re-read: %d pillars, r %.2f, z1 %.1f, walls %s, ceiling %.1f, tour %s"
      % (len(P2), w["pillars"][0]["r"], w["pillars"][0]["z1"], w["arena"]["walls"], w["arena"]["ceiling_z"],
         [c[:2] for c in w["mission"]["corners"]]))
C = np.array([[c[0], c[1]] for c in w["mission"]["corners"]], float)
R_ = w["pillars"][0]["r"]
legs = []
for k in range(len(C) - 1):
    ss = np.linspace(0, 1, 600)[:, None]
    pts = C[k][None, :] + ss * (C[k + 1] - C[k])[None, :]
    legs.append(float(np.min(np.sqrt(((pts[:, None, :] - P2[None, :, :]) ** 2).sum(-1)) - R_)))
print("  the tour's clearance on this field: %s   (worst %+.3f m)"
      % (" ".join("%+.3f" % v for v in legs), min(legs)))
