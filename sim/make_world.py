def generate(cells, cell, radius, seed, min_gap, clear_rect, pad_clearance,
             clear_box=None, clear_band=0.0, circle=0.0, circle_clear=0.0,
             clear_segment=None, segment_band=0.0):
    """Integer-boundary grid; returns (pillars, dropped_for_clear, dropped_for_pad, dropped_for_gap).

    `clear_box` is a METRIC rectangle (x0, x1, y0, y1) and `clear_band` an extra margin around it: any
    pillar whose centre lies inside the box grown by the band is dropped.  The cell-aligned `clear_rect`
    cannot express "the 6 x 4 m mission square plus a margin" on a 2 m grid, because its granularity is a
    whole cell -- MEASURED 2026-10-14, user's spec: 12 x 12 m of 2 x 2 m cells (36 pillars of r = 0.3 m),
    a 6 x 4 m flight square, and the pillars near the square removed.

    `circle` is mission B's flight circle (radius about the origin) and `circle_clear` the free space that
    must be left between that circle and a pillar's SURFACE.  `circle_clear = 0` clears NOTHING -- the
    user's 2026-10-14 spec is a forest over the whole 24 x 24 m region with the circle flown through it,
    and whether the circle is carved out is a decision that must be measured (the audit below reports how
    many pillars actually stand in it) rather than assumed by the generator.
    """
    rng = random.Random(seed)
    half = cells // 2                      # centres at +-0.5 ... +-(half-0.5)
    centres = [(i + 0.5) * cell for i in range(-half, half)]
    placed = []
    n_clear = n_pad = n_gap = 0
    for cx in centres:
        for cy in centres:
            lim = max(0.0, (cell - 2.0 * radius - min_gap) / 2.0)
            here = None
            for _ in range(80):
                px = cx + (rng.uniform(-lim, lim) if lim else 0.0)
                py = cy + (rng.uniform(-lim, lim) if lim else 0.0)
                if clear_rect:
                    x0, x1, y0, y1 = clear_rect
                    # a pillar is dropped if its SURFACE would enter the rectangle: the reserved
                    # region is free space, not just free of centres
                    if (x0 - radius <= px <= x1 + radius) and (y0 - radius <= py <= y1 + radius):
                        here = "clear"
                        break
                if clear_box:
                    bx0, bx1, by0, by1 = clear_box
                    dx = max(bx0 - px, 0.0, px - bx1)
                    dy = max(by0 - py, 0.0, py - by1)
                    # SURFACE-aware, like the clear_rect rule above: the band is the free space left
                    # between the pillar's surface and the square, not between its centre and the square.
                    # MEASURED 2026-10-14: with a centre-based band the 2 m grid still left a pillar
                    # 0.428 m from the square, i.e. 78 mm outside the 0.35 m half footprint.
                    if math.hypot(dx, dy) < clear_band + radius:
                        here = "clear"
                        break
                if circle > 0 and circle_clear > 0 \
                        and abs(math.hypot(px, py) - circle) < radius + circle_clear:
                    # the same SURFACE-aware rule, for mission B's circle: what is reserved is the
                    # band of free space between the circle and the pillar, not a disc of centres
                    here = "clear"
                    break
                if clear_segment and segment_band > 0:
                    # and again for the radial entry leg from the pad to the circle: the pad sits in a
                    # pocket between four cells, so without this the mission's FIRST leg is the one that
                    # cannot be flown (MEASURED 2026-10-14: the circle cleared to +0.828 m still left the
                    # entry leg at +0.278 m, i.e. 72 mm inside the 0.35 m footprint)
                    (sx, sy), (ex, ey) = clear_segment
                    dx, dy = ex - sx, ey - sy
                    L2 = dx * dx + dy * dy
                    t = 0.0 if L2 == 0 else max(0.0, min(1.0, ((px - sx) * dx + (py - sy) * dy) / L2))
                    if math.hypot(px - (sx + t * dx), py - (sy + t * dy)) < radius + segment_band:
                        here = "clear"
                        break
                if math.hypot(px, py) - radius < pad_clearance:
                    here = "pad"
                    break
                if min_gap > 0 and any(math.hypot(px - qx, py - qy) < 2.0 * radius + min_gap
                                       for qx, qy in placed):
                    continue
                placed.append((px, py))
                break
            else:
                here = "gap"
            if here == "clear":
                n_clear += 1
            elif here == "pad":
                n_pad += 1
            elif here == "gap":
                n_gap += 1
    return [(x, y, radius) for x, y in placed], n_clear, n_pad, n_gap


def circle_report(pillars, radius, circle, footprint, circle_clear):
    """How much of mission B's circle is actually flyable -- measured, in pillars, not in adjectives.

    Three numbers, because they answer three different questions:
      * `through`  -- pillars whose DISC the circle crosses (|d - R| < radius): the commanded path is
                      geometrically impossible, no vehicle can fly it, whatever its size;
      * `footprint`-- pillars closer than the clearance CONTRACT (0.20 m since 2026-10-14; it was 0.35 m)
                      to the circle: the commanded path passes, but the promise does not;
      * `nearest`  -- the smallest surface clearance the circle has to any pillar, signed.
    """
    if circle <= 0:
        return []
    rows = []
    through, inside_fp = [], []
    worst = (1e9, None)
    for (px, py, pr) in pillars:
        d = math.hypot(px, py)
        clr = abs(d - circle) - pr
        if clr < worst[0]:
            worst = (clr, (px, py))
        if abs(d - circle) < pr:
            through.append((px, py))
        if clr < footprint:
            inside_fp.append((px, py))
    rows.append("#   mission B circle: centre (0.000, 0.000), radius %.2f m, %d pillars in the region"
                % (circle, len(pillars)))
    rows.append("#     pillars the circle crosses (|d - R| < r): %d of %d" % (len(through), len(pillars)))
    rows.append("#     pillars closer than the %.2f m half footprint: %d of %d"
                % (footprint, len(inside_fp), len(pillars)))
    rows.append("#     nearest pillar surface to the circle: %+.3f m (pillar at %+.3f, %+.3f)"
                % (worst[0], worst[1][0], worst[1][1]) if worst[1] else "")
    rows.append("#     free corridor between neighbouring pillars: 2 x r + gap, see the gap line above")
    rows.append("#     pillars cleared for the circle: band %.2f m -> see 'cells dropped' below"
                % circle_clear)
    return rows


def audit(pillars, radius, clear_rect, cells, cell, min_gap, pad_clearance, dropped, square,
          circle=0.0, circle_clear=0.0, footprint=0.20):
    n = len(pillars)
    out = []
    out.append("#   %d pillars of radius %.2f m in a %.0f x %.0f m arena (%d cells, %d empty)"
               % (n, radius, cells * cell, cells * cell, cells * cells - n,
                  cells * cells - n))
    out.append("#   corridor: min surface gap requested %.2f m" % min_gap)
    gaps = []
    for a in range(n):
        best = 1e9
        for b in range(n):
            if a != b:
                d = math.hypot(pillars[a][0] - pillars[b][0], pillars[a][1] - pillars[b][1])
                best = min(best, d)
        gaps.append(best - 2 * radius)
    if gaps:
        out.append("#   measured pillar-to-pillar surface gap: min %.3f m, median %.3f m"
                   % (min(gaps), sorted(gaps)[len(gaps) // 2]))
    # pad clearance, measured
    if n:
        dmin = min(math.hypot(p[0], p[1]) - radius for p in pillars)
        out.append("#   measured clearance from the origin to the nearest pillar surface: %.3f m "
                   "(requested %.2f)" % (dmin, pad_clearance))
    # the clear rectangle must be EMPTY of cylinders, surface included
    if clear_rect:
        x0, x1, y0, y1 = clear_rect
        inside = [p for p in pillars
                  if (x0 - radius <= p[0] <= x1 + radius) and (y0 - radius <= p[1] <= y1 + radius)]
        ncells = int((x1 - x0) / cell) * int((y1 - y0) / cell)
        out.append("#   clear rectangle x[%g, %g] y[%g, %g] (%d cells): %s"
                   % (x0, x1, y0, y1, ncells, "EMPTY of cylinders" if not inside
                      else "NOT EMPTY (%d pillars)" % len(inside)))
        # and the thing that actually matters: clearance to the mission square itself
        sx0, sy0, sx1, sy1 = square
        sq = [(sx0, sy0), (sx1, sy0), (sx1, sy1), (sx0, sy1), (sx0, sy0)]
        worst = 1e9
        for p in pillars:
            for k in range(4):
                (ax, ay), (bx, by) = sq[k], sq[k + 1]
                dx, dy = bx - ax, by - ay
                L2 = dx * dx + dy * dy
                t = max(0.0, min(1.0, ((p[0] - ax) * dx + (p[1] - ay) * dy) / L2))
                worst = min(worst, math.hypot(p[0] - (ax + t * dx), p[1] - (ay + t * dy)) - radius)
        out.append("#   square flown: x[%g, %g] y[%g, %g] (centred in the clear rectangle)"
                   % (sx0, sx1, sy0, sy1))
        out.append("#   worst pillar-surface clearance to the square: %.3f m  "
                   "(the clearance contract is %.2f m; it was 0.35 m before 2026-10-14)" % (worst, footprint))
    out.append("#   cells dropped: %d for the clear rectangle, %d for pad clearance, %d by the gap rule"
               % (dropped[0], dropped[1], dropped[2]))
    out.extend(circle_report(pillars, radius, circle, footprint, circle_clear))
    return "\n".join(out)


