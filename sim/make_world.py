#!/usr/bin/env python3
"""Generate the pillar forest and write worlds/pillars.yaml.

Spec as the user stated it (2026-10-13):

  * a grid of 1 m x 1 m cells with **integer boundaries** (so "the cells x 0-3, y 0-2" are exactly six
    grid cells), one pillar of radius r per cell, placed randomly inside its cell;
  * a **clear rectangle** -- the six cells x in [0, 3], y in [0, 2] -- which must contain no cylinder
    at all.  That rectangle is what mission A flies its 2.0 x 1.2 m square in, and it is not centred on
    the pad: the square runs from the pad North and East.
  * a **pad clearance** around the origin, because with integer boundaries the origin is a *corner* of
    four cells and a pillar 0.7 m away would be inside the airframe while it sits on the pad.

The generator is parameterised and the seed is written into the file, so the world is reproducible and
re-rolling it is one flag.  It audits its own output: corridor width, clearance to the square, pad
clearance, and whether the clear rectangle really is empty.

Usage:
    python3 make_world.py --cells 10 --cell 1.0 --radius 0.30 --min-gap 0.8 \
        --clear-rect 0,3,0,2 --pad-clearance 0.8 --out ../worlds/pillars.yaml
"""
from __future__ import annotations

import argparse
import math
import os
import random

TEMPLATE_HEAD = """\
# GENERATED by sim/make_world.py --seed {seed} --cells {cells} --cell {cell} --radius {radius}
# --min-gap {min_gap} --clear-rect {rect} --pad-clearance {pad_clear}
# Do not hand-edit the pillar list; re-run the generator so the world stays reproducible.
#
# Frame: local ENU-like, x = East, y = North, z = Up, origin at the take-off point (the pad).
# Grid: {cells}x{cells} cells of {cell} m with integer boundaries, i.e. cell centres at +-0.5, +-1.5, ...
# One pillar of radius {radius} m per cell, randomly placed inside it, never closer than {min_gap} m
# (surface to surface) to another pillar, and never inside the reserved regions below.
#
# Reserved:
#   clear rectangle  x in [{rx0}, {rx1}], y in [{ry0}, {ry1}]   ({ncells} cells, mission A)
#   pad clearance    {pad_clear} m radius around the origin
#
# Audit (computed by the generator):
{audit}
pillars:
"""

# NOTE: this tail is substituted with str.replace(), NOT str.format().  ArduPilot's yaml has literal
# braces (mount: {x: 0.05, ...}), and format() reads those as placeholders -- which is exactly how the
# first version of this file died with "KeyError: 'x'" and silently wrote no world at all.
TEMPLATE_TAIL = """
# The attitude the vehicle is parked in when the LIO initialises.  THIS is what decides the LIO world's
# yaw: the fork's kf_init removes the body's heading from its world, so L's x-axis becomes the body's
# forward axis at that instant.  Facing North (yaw 0) makes the FCU's local NED the textbook NED of this
# world -- (x, y, z)_ned = (N, E, -U) -- with no rotation anywhere in the mission path; facing East would
# make L coincide with W's axes but would rotate the FCU's "North" onto East.  The two cannot both hold,
# and the FCU link is the one that must be provable: see docs/FRAMES.md section 0.3.
spawn:
  x: 0.0
  y: 0.0
  z: @SPAWN_Z@
  yaw_deg: @SPAWN_YAW@        # 0 = the body's x-axis points North (W's +y)

# Where the vehicle sits before take-off.  The origin of this world is the PAD, i.e. the pad centre at
# ground level; the vehicle's own origin starts @SPAWN_Z@ m above it, which is the one constant between
# the LIO's zero and this world's zero (see FRAMES.md 0.3, item 1).
pad:
  x: 0.0
  y: 0.0
  radius: 0.35
  height: @SPAWN_Z@

arena:
  floor_z: 0.0
  ceiling_z: 4.5
  walls:
    x: [@WLO@, @WHI@]
    y: [@WLO@, @WHI@]

sensor:
  frame: mid360_link
  mount: {x: 0.05, y: 0.0, z: 0.10, roll: 0.0, pitch: @MOUNT_PITCH@, yaw: 0.0}
  pattern_file: mid360_pattern.csv
  scan_rate_hz: 10.0
  points_per_scan: 20000
  range_min: 0.10
  range_max: 40.0
  range_noise_sigma: 0.02
  range_resolution: 0.0
  blind_zone: 0.10

imu:
  rate_hz: 200.0
  gyro_noise_sigma: 2.0e-4
  accel_noise_sigma: 2.0e-2
  gyro_bias: [0.0, 0.0, 0.0]
  accel_bias: [0.0, 0.0, 0.0]
  gravity_norm: 9.7946

# Mission A: the 2.0 x 1.2 m square, CENTRED IN THE CLEAR RECTANGLE so every leg keeps a margin wider
# than the vehicle's half footprint.  An earlier version started the square at the pad, which put its
# western leg exactly on the rectangle boundary -- measured pillar clearance 0.200 m, less than the
# 0.35 m half footprint, i.e. the rotor disc would have clipped a pillar.
mission:
  takeoff_alt: 2.5
  hold_s: 3.0
  corners:
    - [@SX0@, @SY0@, 2.0]
    - [@SX1@, @SY0@, 2.0]
    - [@SX1@, @SY1@, 2.0]
    - [@SX0@, @SY1@, 2.0]
    - [@SX0@, @SY0@, 2.0]
  square: [@SX0@, @SY0@, @SX1@, @SY1@]

mission_b:
  takeoff_alt: 2.0
  goal: [3.0, 4.0]

fake_truth:
  rate_hz: 400.0
  speed: 0.20
  climb_s: 8.0
"""


def generate(cells, cell, radius, seed, min_gap, clear_rect, pad_clearance):
    """Integer-boundary grid; returns (pillars, dropped_for_clear, dropped_for_pad, dropped_for_gap)."""
    rng = random.Random(seed)
    half = cells // 2                      # centres at +-0.5 ... +-(half-0.5)
    centres = [(i + 0.5) * cell for i in range(-half, half)]
    placed = []
    n_clear = n_pad = n_gap = 0
    for cx in centres:
        for cy in centres:
            lim = max(0.0, (cell - 2.0 * radius - min_gap) / 2.0)
            here = None
            for _ in range(80):
                px = cx + (rng.uniform(-lim, lim) if lim else 0.0)
                py = cy + (rng.uniform(-lim, lim) if lim else 0.0)
                if clear_rect:
                    x0, x1, y0, y1 = clear_rect
                    # a pillar is dropped if its SURFACE would enter the rectangle: the reserved
                    # region is free space, not just free of centres
                    if (x0 - radius <= px <= x1 + radius) and (y0 - radius <= py <= y1 + radius):
                        here = "clear"
                        break
                if math.hypot(px, py) - radius < pad_clearance:
                    here = "pad"
                    break
                if min_gap > 0 and any(math.hypot(px - qx, py - qy) < 2.0 * radius + min_gap
                                       for qx, qy in placed):
                    continue
                placed.append((px, py))
                break
            else:
                here = "gap"
            if here == "clear":
                n_clear += 1
            elif here == "pad":
                n_pad += 1
            elif here == "gap":
                n_gap += 1
    return [(x, y, radius) for x, y in placed], n_clear, n_pad, n_gap


def audit(pillars, radius, clear_rect, cells, cell, min_gap, pad_clearance, dropped, square):
    n = len(pillars)
    out = []
    out.append("#   %d pillars of radius %.2f m in a %.0f x %.0f m arena (%d cells, %d empty)"
               % (n, radius, cells * cell, cells * cell, cells * cells - n,
                  cells * cells - n))
    out.append("#   corridor: min surface gap requested %.2f m" % min_gap)
    gaps = []
    for a in range(n):
        best = 1e9
        for b in range(n):
            if a != b:
                d = math.hypot(pillars[a][0] - pillars[b][0], pillars[a][1] - pillars[b][1])
                best = min(best, d)
        gaps.append(best - 2 * radius)
    if gaps:
        out.append("#   measured pillar-to-pillar surface gap: min %.3f m, median %.3f m"
                   % (min(gaps), sorted(gaps)[len(gaps) // 2]))
    # pad clearance, measured
    if n:
        dmin = min(math.hypot(p[0], p[1]) - radius for p in pillars)
        out.append("#   measured clearance from the origin to the nearest pillar surface: %.3f m "
                   "(requested %.2f)" % (dmin, pad_clearance))
    # the clear rectangle must be EMPTY of cylinders, surface included
    if clear_rect:
        x0, x1, y0, y1 = clear_rect
        inside = [p for p in pillars
                  if (x0 - radius <= p[0] <= x1 + radius) and (y0 - radius <= p[1] <= y1 + radius)]
        ncells = int((x1 - x0) / cell) * int((y1 - y0) / cell)
        out.append("#   clear rectangle x[%g, %g] y[%g, %g] (%d cells): %s"
                   % (x0, x1, y0, y1, ncells, "EMPTY of cylinders" if not inside
                      else "NOT EMPTY (%d pillars)" % len(inside)))
        # and the thing that actually matters: clearance to the mission square itself
        sx0, sy0, sx1, sy1 = square
        sq = [(sx0, sy0), (sx1, sy0), (sx1, sy1), (sx0, sy1), (sx0, sy0)]
        worst = 1e9
        for p in pillars:
            for k in range(4):
                (ax, ay), (bx, by) = sq[k], sq[k + 1]
                dx, dy = bx - ax, by - ay
                L2 = dx * dx + dy * dy
                t = max(0.0, min(1.0, ((p[0] - ax) * dx + (p[1] - ay) * dy) / L2))
                worst = min(worst, math.hypot(p[0] - (ax + t * dx), p[1] - (ay + t * dy)) - radius)
        out.append("#   square flown: x[%g, %g] y[%g, %g] (centred in the clear rectangle)"
                   % (sx0, sx1, sy0, sy1))
        out.append("#   worst pillar-surface clearance to the square: %.3f m  "
                   "(the vehicle's half footprint is ~0.35 m)" % worst)
    out.append("#   cells dropped: %d for the clear rectangle, %d for pad clearance, %d by the gap rule"
               % (dropped[0], dropped[1], dropped[2]))
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cells", type=int, default=10, help="even number: integer boundaries then")
    ap.add_argument("--cell", type=float, default=1.0)
    ap.add_argument("--radius", type=float, default=0.30)
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--min-gap", type=float, default=0.8,
                    help="minimum pillar-to-pillar SURFACE gap (the corridor the vehicle needs)")
    ap.add_argument("--clear-rect", default="0,3,0,2",
                    help="X0,X1,Y0,Y1 kept free of cylinders (mission A); empty string to disable")
    ap.add_argument("--pad-clearance", type=float, default=0.8,
                    help="free radius around the origin, since with integer boundaries the pad sits "
                         "on a corner of four cells")
    ap.add_argument("--mount-pitch", type=float, default=45.0,
                    help="lidar mount pitch in degrees.  DECIDED 2026-10-13: 45 deg nose-down, matching "
                         "the real aircraft -- a level mount would put the MID-360's -7..+52 deg fan "
                         "about the body, i.e. ceiling only and almost no floor, and the vertical "
                         "channel would lose its best constraint (at 0.5 m: 23.5 %% of returns are "
                         "floor with 45 deg, ~0 %% with 0 deg).  Set 0 only for an A/B experiment")
    ap.add_argument("--spawn-z", type=float, default=0.205,
                    help="height of the vehicle origin above the pad at spawn (the pad's own height)")
    ap.add_argument("--spawn-yaw", type=float, default=0.0,
                    help="body heading at spawn, degrees, 0 = North.  This decides the LIO world's yaw; "
                         "see the comment in the emitted file and docs/FRAMES.md 0.3")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                                  "..", "worlds", "pillars.yaml"))
    args = ap.parse_args()

    clear = tuple(float(v) for v in args.clear_rect.split(",")) if args.clear_rect else None
    pillars, nc, np_, ng = generate(args.cells, args.cell, args.radius, args.seed, args.min_gap,
                                    clear, args.pad_clearance)
    # the square is centred in the clear rectangle, so every leg keeps a margin wider than the
    # vehicle: starting it at the pad put one leg exactly on the rectangle boundary (measured
    # clearance 0.200 m, less than the 0.35 m half footprint)
    if clear:
        sx0 = (clear[0] + clear[1]) / 2.0 - 1.0
        sy0 = (clear[2] + clear[3]) / 2.0 - 0.6
    else:
        sx0, sy0 = 0.0, 0.0
    square = (sx0, sy0, sx0 + 2.0, sy0 + 1.2)
    halfw = args.cells * args.cell / 2.0
    rect_txt = ("%g,%g,%g,%g" % clear) if clear else "none"
    ncell = int((clear[1] - clear[0]) / args.cell) * int((clear[3] - clear[2]) / args.cell) if clear \
        else 0
    head = TEMPLATE_HEAD.format(
        seed=args.seed, cells=args.cells, cell=args.cell, radius=args.radius, min_gap=args.min_gap,
        rect=rect_txt, pad_clear=args.pad_clearance, rx0=clear[0] if clear else 0,
        rx1=clear[1] if clear else 0, ry0=clear[2] if clear else 0, ry1=clear[3] if clear else 0,
        ncells=ncell,
        audit=audit(pillars, args.radius, clear, args.cells, args.cell, args.min_gap,
                    args.pad_clearance, (nc, np_, ng), square))
    body = "".join("  - {x: %+.3f, y: %+.3f, r: %.2f, z0: 0.0, z1: 4.2}\n" % p for p in pillars)
    tail = (TEMPLATE_TAIL.replace("@WLO@", "%.1f" % -halfw).replace("@WHI@", "%.1f" % halfw)
            .replace("@SX0@", "%.1f" % square[0]).replace("@SX1@", "%.1f" % square[2])
            .replace("@SY0@", "%.1f" % square[1]).replace("@SY1@", "%.1f" % square[3])
            .replace("@SPAWN_Z@", "%.3f" % args.spawn_z)
            .replace("@SPAWN_YAW@", "%.1f" % args.spawn_yaw)
            .replace("@MOUNT_PITCH@", "%.1f" % args.mount_pitch))
    # VERIFY THE SUBSTITUTION LANDED.  An earlier version of this generator silently dropped the pad
    # block (a rewrite lost it) and a patch script printed "updated" while the replace had not matched
    # at all -- the same failure mode the project's rule 3 exists for: a change must be verified to have
    # reached its consumer, and a generator is a consumer of its own template.
    for tok in ("@WLO@", "@WHI@", "@SX0@", "@SY0@", "@SPAWN_Z@", "@SPAWN_YAW@", "@MOUNT_PITCH@"):
        if tok in tail or tok in head:
            raise SystemExit("template token %s was not substituted" % tok)
    for need in ("spawn:", "pad:", "arena:", "pillars:"):
        if need not in head + body + tail:
            raise SystemExit("emitted world is missing the %s block" % need)
    with open(args.out, "w") as fh:
        fh.write(head + body + tail)
    print("wrote %s" % args.out)
    print("  %d pillars, radius %.2f, %dx%d cells of %.1f m, seed %d"
          % (len(pillars), args.radius, args.cells, args.cells, args.cell, args.seed))
    print(audit(pillars, args.radius, clear, args.cells, args.cell, args.min_gap,
                args.pad_clearance, (nc, np_, ng), square))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
